/**
 * Writes examples/vectors.json from the public BIP39 test phrase "abandon ... about". The phrase is public and holds
 * no funds; never use it for a real wallet. Re-running changes only the Nostr event signature (BIP-340 uses fresh
 * auxiliary randomness); everything else is deterministic. Usage: npx tsx scripts/make-vectors.ts
 */
import { writeFileSync } from 'node:fs';
import { binToHex } from '@bitauth/libauth';
import { BCH_PATH, NOSTR_PATH, bindingFromKeys, keysFromPhrase } from '../src/core/paytaca.js';

const PHRASE = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';
const CREATED_AT = 1763251200; // 2025-11-16 00:00:00 UTC, fixed so the vector is stable

const main = keysFromPhrase(PHRASE, 'bitcoincash');
const test = keysFromPhrase(PHRASE, 'bchtest');
const event = bindingFromKeys(main, CREATED_AT, { content: '', tags: [['i', 'github:example', 'abc123']] });
const claim = event.tags.find((t) => t[0] === 'i' && t[1]?.startsWith('bch:'));

const vectors = {
  note: 'Generated by scripts/make-vectors.ts from the public BIP39 test phrase. Do not use these keys for funds.',
  phrase: PHRASE,
  paths: { bch: BCH_PATH, nostr: NOSTR_PATH },
  nostr: { pubkey: main.nostrPubkey, npub: main.npub },
  bch: {
    publicKey: binToHex(main.bchPublicKey),
    address: { bitcoincash: main.address, bchtest: test.address },
  },
  signedTextNote: 'The BCH key signs the NIP-39 verification text built from nostr.npub (see verificationText in src/core/nostr.ts).',
  bchSignature: claim?.[2],
  bindingEvent: { id: event.id, pubkey: event.pubkey, created_at: event.created_at, kind: event.kind, tags: event.tags, content: event.content, sig: event.sig },
  external: {
    note: 'Signed-message vector published with the bitcoinjs-message library (uncompressed key, header 27). Signature and address only.',
    message: 'This is an example of a signed message.',
    signature: 'G9L5yLFjti0QTHhPyFrZCT1V/MMnBtXKmoiKDZ78NDBjERki6ZTQZdSMCtkgoNmp17By9ItJr8o7ChX0XxY91nk=',
    legacyAddress: '1HZwkjkeaoZfTSaJxDw6aKkxp45agDiEzN',
  },
};
writeFileSync(new URL('../examples/vectors.json', import.meta.url), `${JSON.stringify(vectors, null, 2)}\n`);
writeFileSync(new URL('../examples/binding-event.json', import.meta.url), `${JSON.stringify(vectors.bindingEvent, null, 2)}\n`);
console.log('wrote examples/vectors.json and examples/binding-event.json');
